// ── Core i18n engine ──────────────────────────────────────────────────────────
const I18N = {
  current: localStorage.getItem('rm-lang') || 'he',

  get(key) {
    return TRANSLATIONS[this.current]?.[key] || TRANSLATIONS['he'][key] || key;
  },

  setLang(lang) {
    if (!TRANSLATIONS[lang]) return;
    this.current = lang;
    localStorage.setItem('rm-lang', lang);
    this.apply();
  },

  apply() {
    const t = TRANSLATIONS[this.current];
    // Direction
    document.documentElement.lang = t.lang;
    document.documentElement.dir  = t.dir;

    // Translate all data-i18n elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.dataset.i18n;
      const val = t[key] || TRANSLATIONS['he'][key];
      if (val) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.placeholder = val;
        } else {
          el.textContent = val;
        }
      }
    });

    // Mark active language button
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.classList.toggle('active', btn.dataset.lang === this.current);
    });
  }
};

// Run after DOM ready
document.addEventListener('DOMContentLoaded', () => {
  // Small delay so components.js injects header first
  setTimeout(() => {
    I18N.apply();

    // Attach click handlers to language buttons
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.addEventListener('click', () => I18N.setLang(btn.dataset.lang));
    });
  }, 80);
});
